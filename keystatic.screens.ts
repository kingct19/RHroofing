function screen(
  label: string,
  path: string,
  previewUrl: string,
  schema: Parameters<typeof singleton>[0]["schema"],
) {
  return singleton({
    label,
    path,
    format: { data: "json" },
    entryLayout: "form",
    previewUrl,
    schema,
  });
}

const photos = (label: string) =>
  fields.array(
    fields.object({
      src: siteImage("Photo"),
      alt: requiredText("What is in this photo", "This name is what you see in the list."),
    }),
    { label, itemLabel: (props) => props.fields.alt.value || "Photo" },
  );

const factList = (label: string) =>
  fields.array(
    fields.object({
      label: requiredText("Label"),
      value: requiredText("Value"),
    }),
    { label, itemLabel: (props) => props.fields.label.value || "Fact" },
  );

const linkList = (label: string) =>
  fields.array(
    fields.object({
      label: requiredText("Words"),
      href: requiredText("Where it goes", "Example: /gallery"),
    }),
    { label, itemLabel: (props) => props.fields.label.value || "Link" },
  );

